/// SwapBaseIn instruction parameters.
///
/// Uses 1-byte instruction index (0x09).
#[derive(Debug, Clone, borsh::BorshDeserialize, borsh::BorshSerialize, InstructionData)]
#[instruction_data(discriminator = [SWAP_BASE_IN_IX], discriminator_size = 1, unverified = "this protocol is not modelled to the pumpfun/pumpswap standard yet; pinning params here would claim a verification the rest of the vertical does not have")]
pub struct SwapBaseInParams {
    /// Amount of tokens to swap in.
    pub amount_in: u64,
    /// Minimum amount of tokens to receive (slippage protection).
    pub minimum_amount_out: u64,
}

impl SwapBaseInParams {
    /// Create new swap parameters.
    #[must_use]
    pub fn new(amount_in: u64, minimum_amount_out: u64) -> Self {
        Self {
            amount_in,
            minimum_amount_out,
        }
    }

    /// Create parameters from swap output with slippage.
    ///
    /// For a buy: amount_in = SOL, minimum_amount_out = tokens (with slippage).
    /// For a sell: amount_in = tokens, minimum_amount_out = SOL (with slippage).
    #[must_use]
    pub fn from_swap_output(amount_in: u64, expected_out: u64, slippage_bps: u16) -> Self {
        let min_out = (expected_out as u128 * (10000 - slippage_bps as u128) / 10000) as u64;
        Self {
            amount_in,
            minimum_amount_out: min_out,
        }
    }
}

