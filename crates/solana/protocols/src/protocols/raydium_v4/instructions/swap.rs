impl SwapBaseInAccounts {
    /// Create swap accounts from pool keys and user.
    ///
    /// For a buy (SOL→token): source = quote ATA, dest = base ATA.
    /// For a sell (token→SOL): source = base ATA, dest = quote ATA.
    #[must_use]
    pub fn from_keys(
        keys: &RaydiumV4Keys,
        user: &Pubkey,
        source_mint: &Pubkey,
        dest_mint: &Pubkey,
    ) -> Self {
        SwapBaseInAccounts {
            token_program: spl_token::id(),
            amm_id: keys.amm_id,
            amm_authority: keys.amm_authority,
            amm_open_orders: keys.amm_open_orders,
            amm_target_orders: keys.amm_target_orders,
            pool_coin_token_account: keys.base_vault,
            pool_pc_token_account: keys.quote_vault,
            serum_program_id: keys.serum_program_id,
            serum_market: keys.serum_market,
            serum_bids: keys.serum_bids,
            serum_asks: keys.serum_asks,
            serum_event_queue: keys.serum_event_queue,
            serum_coin_vault_account: keys.serum_coin_vault,
            serum_pc_vault_account: keys.serum_pc_vault,
            serum_vault_signer: keys.serum_vault_signer,
            user_source_token_account: get_associated_token_address(user, source_mint),
            user_destination_token_account: get_associated_token_address(user, dest_mint),
            user_source_owner: *user,
        }
    }

    /// Create buy accounts (SOL → base token).
    #[must_use]
    pub fn for_buy(keys: &RaydiumV4Keys, user: &Pubkey) -> Self {
        Self::from_keys(keys, user, &keys.quote_mint, &keys.base_mint)
    }

    /// Create sell accounts (base token → SOL).
    #[must_use]
    pub fn for_sell(keys: &RaydiumV4Keys, user: &Pubkey) -> Self {
        Self::from_keys(keys, user, &keys.base_mint, &keys.quote_mint)
    }
}

